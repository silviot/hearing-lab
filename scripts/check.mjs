import { access, readFile, readdir, stat } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, extname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCE_ARCHIVE } from './archive.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const excluded = new Set(['.git', 'node_modules', 'dist', 'coverage', '.sites-runtime', '.openai']);
const failures = [];
let checkedLinks = 0;
let checkedModules = 0;

async function files(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (excluded.has(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await files(path));
    else if (entry.isFile()) found.push(path);
  }
  return found;
}

async function localLink(file, target, { webAsset = false } = {}) {
  if (!target || /^(?:[a-z][a-z\d+.-]*:|\/\/|#|\{)/i.test(target)) return;
  if (target.includes('${')) return;
  let clean;
  try { clean = decodeURIComponent(target.split(/[?#]/, 1)[0]); }
  catch { failures.push(`${relative(root, file)}: invalid URL encoding ${target}`); return; }
  if (!clean) return;
  if (webAsset && clean.startsWith('/')) {
    failures.push(`${relative(root, file)}: use a relative asset path for subpath hosting: ${target}`);
  }
  const destination = clean.startsWith('/') ? resolve(root, `.${clean}`) : resolve(dirname(file), clean);
  const rel = relative(root, destination);
  if (rel === '..' || rel.startsWith('../') || isAbsolute(rel)) {
    failures.push(`${relative(root, file)}: local link leaves the project: ${target}`);
    return;
  }
  // This fixed file is generated by build.mjs, not checked into the source tree.
  if (rel === SOURCE_ARCHIVE) { checkedLinks += 1; return; }
  try { await access(destination); checkedLinks += 1; }
  catch { failures.push(`${relative(root, file)}: missing local file ${target}`); }
}

for (const file of await files(root)) {
  const extension = extname(file);
  if (extension === '.js' || extension === '.mjs') {
    const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
    if (result.status !== 0) failures.push(`${relative(root, file)}: ${result.stderr || result.error?.message || 'syntax check failed'}`);
    checkedModules += 1;
    const source = await readFile(file, 'utf8');
    const importPattern = /(?:\b(?:import|export)\s+(?:[^;\n]*?\s+from\s*)?|\bimport\s*\()\s*['"]([^'"]+)['"]/g;
    for (const match of source.matchAll(importPattern)) {
      if (match[1].startsWith('.')) await localLink(file, match[1], { webAsset: true });
    }
  } else if (extension === '.html') {
    const source = await readFile(file, 'utf8');
    for (const match of source.matchAll(/\b(?:src|href)\s*=\s*['"]([^'"]+)['"]/g)) {
      await localLink(file, match[1], { webAsset: true });
    }
  } else if (extension === '.css') {
    const source = await readFile(file, 'utf8');
    for (const match of source.matchAll(/url\(\s*['"]?([^)'"\s]+)['"]?\s*\)/g)) {
      await localLink(file, match[1], { webAsset: true });
    }
  } else if (extension === '.md') {
    const source = (await readFile(file, 'utf8')).replace(/```[\s\S]*?```/g, '');
    for (const match of source.matchAll(/\]\(([^\s)]+)(?:\s+"[^"]*")?\)/g)) await localLink(file, match[1]);
  } else if (extension === '.json') {
    try { JSON.parse(await readFile(file, 'utf8')); }
    catch (error) { failures.push(`${relative(root, file)}: ${error.message}`); }
  }
}

const packageInfo = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
if (packageInfo.type !== 'module') failures.push('package.json must declare type: module.');
if (packageInfo.license !== 'AGPL-3.0-only') failures.push('package.json must declare AGPL-3.0-only.');
if (Object.keys(packageInfo.dependencies ?? {}).length || Object.keys(packageInfo.devDependencies ?? {}).length) {
  failures.push('This project is dependency-free; review any new dependencies explicitly.');
}
const license = await readFile(join(root, 'LICENSE'), 'utf8');
if (license.length < 30000 || !license.startsWith('GNU AFFERO GENERAL PUBLIC LICENSE') || !license.includes('13. Remote Network Interaction; Use with the GNU General Public License.') || !license.includes('END OF TERMS AND CONDITIONS')) {
  failures.push('LICENSE must contain the complete GNU AGPLv3 text.');
}
for (const required of ['index.html', 'public/icon.svg', 'README.md', 'CONTRIBUTING.md', 'THIRD_PARTY_NOTICES.md']) {
  try { const info = await stat(join(root, required)); if (!info.isFile()) throw new Error(); }
  catch { failures.push(`Required file missing: ${required}`); }
}
if (failures.length) {
  for (const failure of failures) console.error(`FAIL ${failure}`);
  process.exitCode = 1;
} else {
  console.log(`Checks passed: ${checkedModules} JavaScript modules, ${checkedLinks} local file references, JSON and project metadata.`);
}
